const fs = require('fs');

function replaceAll(file, replacements) {
    let content = fs.readFileSync(file, 'utf8');
    for (let [search, replace] of Object.entries(replacements)) {
        content = content.replace(search, replace);
    }
    fs.writeFileSync(file, content, 'utf8');
}

